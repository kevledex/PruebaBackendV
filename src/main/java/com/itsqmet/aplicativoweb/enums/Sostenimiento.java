package com.itsqmet.aplicativoweb.enums;

/**
 * Tipo de sostenimiento de la institución educativa (Art. 2 del Acuerdo
 * Ministerial: "todas las instituciones educativas de todos los
 * sostenimientos... del Sistema Nacional de Educación"). Condiciona la
 * organización de periodos académicos: FISCAL es obligatoriamente
 * TRIMESTRAL (Cap. 2, pág. 5 del Instructivo); los demás pueden elegir.
 */
public enum Sostenimiento {
    FISCAL,
    PARTICULAR,
    FISCOMISIONAL,
    MUNICIPAL
}
